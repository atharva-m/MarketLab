"""Explicit all-62-partition research acceptance against owned migrated services.

No downloads or existing artifact rewrites. Independent reference must be freshly
generated by r4_reference.py scan/numerics. Results stay under ignored artifacts.
"""

import argparse
import asyncio
import hashlib
import json
import platform
import time
from datetime import date, datetime
from pathlib import Path

import sqlalchemy as sa

from marketlab.analytics.bars import BarService
from marketlab.analytics.cache import canonical
from marketlab.config import Settings
from marketlab.datasets.publication import dataset_versions
from marketlab.datasets.source import file_hash
from marketlab.research import store
from marketlab.research.service import ResearchService
from marketlab.research.spec import ResearchSpec

BASE = Path("artifacts/r4")
ROOT = Path("artifacts/r2/historical-storage").resolve()


def snapshot():
    """Retain only the accepted month runs, not fixtures with other storage roots."""
    settings = Settings()
    assert settings.sqlalchemy_url.port == 55434
    accepted = json.loads((BASE / "month-acceptance.json").read_text())
    assert accepted["status"] == "passed" and len(accepted["runs"]) == 10
    identities = [row["run_id"] for row in accepted["runs"]]
    engine = sa.create_engine(settings.sqlalchemy_url, connect_args=settings.database_connect_args)
    try:
        with engine.connect() as connection:
            saved_runs = [
                dict(r)
                for r in connection.execute(
                    sa.select(store.runs).where(store.runs.c.run_id.in_(identities))
                ).mappings()
            ]
            submissions = [r["submission_id"] for r in saved_runs]
            payload = {
                "migration_head": connection.scalar(
                    sa.text("SELECT version_num FROM alembic_version")
                ),
                "storage_root": str(ROOT),
                "accepted_run_ids": identities,
                "research_runs": saved_runs,
            }
            for name, table, column, values in (
                (
                    "research_submissions",
                    store.submissions,
                    store.submissions.c.submission_id,
                    submissions,
                ),
                ("research_attempts", store.attempts, store.attempts.c.run_id, identities),
                ("research_results", store.results, store.results.c.run_id, identities),
            ):
                payload[name] = [
                    dict(r)
                    for r in connection.execute(
                        sa.select(table).where(column.in_(values))
                    ).mappings()
                ]
            payload["dataset_versions"] = [
                dict(r)
                for r in connection.execute(sa.select(dataset_versions)).mappings()
                if r["dataset_version_id"]
                in {
                    item["dataset_version_id"]
                    for item in json.loads(Path("artifacts/r2/catalog-final.json").read_text())[
                        "catalog"
                    ]
                }
            ]
        assert len(payload["research_runs"]) == len(payload["research_results"]) == 10
        assert len(payload["dataset_versions"]) == 62
        (BASE / "catalog-final.json").write_text(
            json.dumps(payload, indent=2, default=str), encoding="utf-8"
        )
    finally:
        engine.dispose()


def restore(engine):
    records = json.loads(Path("artifacts/r2/catalog-final.json").read_text())["catalog"]
    assert len(records) == 62
    with engine.begin() as connection:
        for record in records:
            existing = (
                connection.execute(
                    sa.select(dataset_versions).where(
                        dataset_versions.c.dataset_version_id == record["dataset_version_id"]
                    )
                )
                .mappings()
                .one_or_none()
            )
            if existing:
                assert existing["manifest_sha256"] == record["manifest_sha256"]
                continue
            row = dict(record)
            row["trade_date"] = date.fromisoformat(row["trade_date"])
            row["published_at"] = datetime.fromisoformat(row["published_at"])
            connection.execute(dataset_versions.insert().values(**row))
    return records


async def main(prefix):
    settings = Settings()
    # Explicit acknowledgement guard prevents accidental original database use.
    assert settings.sqlalchemy_url.port == 55434
    engine = sa.create_engine(settings.sqlalchemy_url, connect_args=settings.database_connect_args)
    records = restore(engine)
    references = json.loads((BASE / "reference-workflows.json").read_text())
    assert len(references) == 5
    bars = BarService(engine, ROOT, settings.redis_url.get_secret_value())
    service = ResearchService(bars)
    evidence = {
        "status": "running",
        "hardware": platform.platform(),
        "peak_memory": "unmeasured",
        "input_rows": sum(r["row_count"] for r in records),
        "partitions": 62,
        "execution": service.execution,
        "runs": [],
    }
    started = time.perf_counter()
    try:
        for index, reference in enumerate(references):
            spec = ResearchSpec.create(reference["spec"])
            repeated = []
            for repetition in range(2):
                beginning = time.perf_counter()
                key = f"{prefix}-{index}-{repetition}"
                run, replayed = await service.submit(spec, key)
                assert await service.submit(spec, key) == (run, True)
                await service.work(1, run)
                info = service.inspect(run)
                assert info["state"] == "succeeded", info
                result, result_hash = service.read(run, "results")
                summary, first_cache = await service.summary(run)
                warm_summary, warm_cache = await service.summary(run)
                assert warm_cache == "HIT" and warm_summary == summary
                assert result == reference["results"], f"result mismatch {index}"
                assert summary == reference["summary"], f"summary mismatch {index}"
                assert result_hash == reference["results_sha256"]
                assert hashlib.sha256(canonical(summary)).hexdigest() == reference["summary_sha256"]
                repeated.append(result_hash)
                item = {
                    "index": index,
                    "repetition": repetition,
                    "run_id": run,
                    "workflow": spec.workflow,
                    "symbols": spec.symbols,
                    "replayed": replayed,
                    "result_sha256": result_hash,
                    "summary_sha256": reference["summary_sha256"],
                    "cache": [first_cache, warm_cache],
                    "attempts": info["attempt_count"],
                    "seconds": time.perf_counter() - beginning,
                    "coverage": {s: p["coverage"] for s, p in result["profiles"].items()},
                    "cluster_counts": result.get("cluster_counts"),
                }
                evidence["runs"].append(item)
                (BASE / "month-acceptance.json").write_text(
                    json.dumps(evidence, indent=2), encoding="utf-8"
                )
                print(json.dumps(item), flush=True)
            assert repeated[0] == repeated[1]
        for record in records:
            manifest_path = ROOT / record["manifest_path"]
            assert file_hash(manifest_path) == record["manifest_sha256"]
            manifest = json.loads(manifest_path.read_text())
            assert (
                file_hash(manifest_path.parent / "trades.parquet") == manifest["artifact"]["sha256"]
            )
        evidence["status"] = "passed"
        evidence["seconds"] = time.perf_counter() - started
        evidence["source_hashes_unchanged"] = 62
        (BASE / "month-acceptance.json").write_text(
            json.dumps(evidence, indent=2), encoding="utf-8"
        )
    finally:
        await service.close()
        await bars.close()
        engine.dispose()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--key-prefix")
    parser.add_argument("--export-only", action="store_true")
    args = parser.parse_args()
    if args.export_only:
        snapshot()
    elif args.key_prefix:
        asyncio.run(main(args.key_prefix))
    else:
        parser.error("--key-prefix or --export-only is required")
